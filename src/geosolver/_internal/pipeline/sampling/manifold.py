"""Structure-aware deterministic samplers for Phase 0.

The previous implementation embedded a distance-specific rescue directly in
``run_initial_probe``.  This module turns the same idea into an explicit
strategy portfolio: each sampler declares the mathematical structure it uses,
produces points satisfying that structure, and reports diagnostics under a
strategy id.  That makes adding future samplers (line, circle, angle, branch
manifold, etc.) a general extension point instead of an orchestration patch.
"""

from __future__ import annotations

import ast
from dataclasses import dataclass
import math
from typing import Protocol

from geosolver._internal.pipeline.contracts.candidate_record import FloatCandidate
from geosolver._internal.pipeline.contracts.evaluator_port import EvaluatorPort
from geosolver._internal.pipeline.evaluator.classify_evaluation_failure import EvaluationStatus
from geosolver._internal.pipeline.problem.load_problem_bundle import ProblemBundle
from geosolver.ir.compiler import safe_eval_expr

EXACT_DISTANCE_SAMPLE_COUNT = 12


@dataclass(frozen=True)
class ManifoldSampleResult:
    """Candidates and diagnostics generated by one deterministic sampler."""

    strategy_id: str
    candidates: tuple[FloatCandidate, ...]
    metrics: dict[str, object]


class ManifoldSampleStrategy(Protocol):
    """Protocol for deterministic structure-aware Phase 0 samplers."""

    strategy_id: str

    def sample(
        self,
        *,
        bundle: ProblemBundle,
        evaluator: EvaluatorPort,
        bounds: list[tuple[float, float]],
        existing_candidates: tuple[FloatCandidate, ...],
    ) -> ManifoldSampleResult:
        """Return candidate points derived from problem structure."""


def _resolve_point_coordinates(value: object) -> tuple[float, float] | None:
    x_coord = getattr(value, "x", None)
    y_coord = getattr(value, "y", None)
    if x_coord is None or y_coord is None:
        return None
    try:
        x_value = float(x_coord)
        y_value = float(y_coord)
    except Exception:
        return None
    if not math.isfinite(x_value) or not math.isfinite(y_value):
        return None
    return (x_value, y_value)


def _collect_fixed_point_coordinates(bundle: ProblemBundle) -> dict[str, tuple[float, float]]:
    construction = getattr(bundle.spec, "construction", None)
    if not construction:
        return {}
    resolved: dict[str, tuple[float, float]] = {}
    context = dict(bundle.base_context)
    for item in construction:
        try:
            value = safe_eval_expr(item.expr, context)
        except Exception:
            continue
        context[item.name] = value
        coordinates = _resolve_point_coordinates(value)
        if coordinates is not None:
            resolved[item.name] = coordinates
    return resolved


def _extract_parametric_point_axes(bundle: ProblemBundle) -> dict[str, tuple[int, int]]:
    construction = getattr(bundle.spec, "construction", None)
    if not construction:
        return {}
    axis_by_name = {name: index for index, name in enumerate(bundle.var_names)}
    parametric: dict[str, tuple[int, int]] = {}
    for item in construction:
        try:
            parsed = ast.parse(item.expr, mode="eval")
        except SyntaxError:
            continue
        call = parsed.body
        if not isinstance(call, ast.Call):
            continue
        if not isinstance(call.func, ast.Name) or call.func.id != "Point":
            continue
        if len(call.args) != 2 or call.keywords:
            continue
        first_arg, second_arg = call.args
        if not isinstance(first_arg, ast.Name) or not isinstance(second_arg, ast.Name):
            continue
        first_axis = axis_by_name.get(first_arg.id)
        second_axis = axis_by_name.get(second_arg.id)
        if first_axis is None or second_axis is None:
            continue
        parametric[item.name] = (first_axis, second_axis)
    return parametric


def _extract_exact_distance_constraints(
    bundle: ProblemBundle,
) -> tuple[tuple[tuple[int, int], tuple[float, float], float], ...]:
    """Return directly parameterized circle manifolds induced by Distance(...)=r."""

    spec = getattr(bundle, "spec", None)
    if spec is None:
        return ()
    constraints_exprs = getattr(spec, "constraints", None)
    targets = getattr(bundle, "targets", None)
    if not constraints_exprs or targets is None:
        return ()
    fixed_points = _collect_fixed_point_coordinates(bundle)
    parametric_points = _extract_parametric_point_axes(bundle)
    constraints: list[tuple[tuple[int, int], tuple[float, float], float]] = []
    seen: set[tuple[tuple[int, int], tuple[float, float], float]] = set()
    for constraint_expr, target in zip(constraints_exprs, targets, strict=True):
        if not isinstance(constraint_expr, str):
            continue
        try:
            parsed = ast.parse(constraint_expr, mode="eval")
        except SyntaxError:
            continue
        call = parsed.body
        if not isinstance(call, ast.Call):
            continue
        if not isinstance(call.func, ast.Name) or call.func.id != "Distance":
            continue
        if len(call.args) != 2 or call.keywords:
            continue
        left_arg, right_arg = call.args
        if not isinstance(left_arg, ast.Name) or not isinstance(right_arg, ast.Name):
            continue
        try:
            radius = float(target)
        except Exception:
            continue
        if (not math.isfinite(radius)) or radius <= 0.0:
            continue
        center = fixed_points.get(left_arg.id)
        axes = parametric_points.get(right_arg.id)
        if center is None or axes is None:
            center = fixed_points.get(right_arg.id)
            axes = parametric_points.get(left_arg.id)
        if center is None or axes is None:
            continue
        key = (axes, center, radius)
        if key in seen:
            continue
        seen.add(key)
        constraints.append(key)
    return tuple(constraints)


def _midpoint_bounds(bounds: list[tuple[float, float]]) -> list[float]:
    return [(low + high) / 2.0 for low, high in bounds]


def _is_within_bounds(point: list[float], bounds: list[tuple[float, float]]) -> bool:
    return all(
        low <= value <= high
        for value, (low, high) in zip(point, bounds, strict=True)
    )


@dataclass(frozen=True)
class DistanceCircleSampler:
    """Sample variables constrained to lie on a known circle.

    This is a geometry-primitive strategy, not a problem-specific rescue: it is
    triggered solely by IR structure equivalent to ``Distance(fixed, Point(x,y))
    = r`` with a directly parameterized point.
    """

    sample_count: int = EXACT_DISTANCE_SAMPLE_COUNT
    strategy_id: str = "distance_circle_manifold"

    def sample(
        self,
        *,
        bundle: ProblemBundle,
        evaluator: EvaluatorPort,
        bounds: list[tuple[float, float]],
        existing_candidates: tuple[FloatCandidate, ...],
    ) -> ManifoldSampleResult:
        exact_distance_constraints = _extract_exact_distance_constraints(bundle)
        if not exact_distance_constraints:
            return ManifoldSampleResult(strategy_id=self.strategy_id, candidates=(), metrics={})

        records: list[FloatCandidate] = []
        seen_points = {tuple(candidate.x_float) for candidate in existing_candidates}
        next_candidate_id = max(
            [0, *(int(candidate.candidate_id) for candidate in existing_candidates)],
        )
        base_point = _midpoint_bounds(bounds)
        total_samples = 0
        finite_samples = 0
        guard_pass_samples = 0
        best_residual = math.inf
        best_point: tuple[float, ...] | None = None

        for axes, center, radius in exact_distance_constraints:
            for sample_index in range(int(self.sample_count)):
                angle = (2.0 * math.pi * float(sample_index)) / float(self.sample_count)
                point = list(base_point)
                point[axes[0]] = center[0] + (radius * math.cos(angle))
                point[axes[1]] = center[1] + (radius * math.sin(angle))
                if not _is_within_bounds(point, bounds):
                    continue
                point_key = tuple(point)
                if point_key in seen_points:
                    continue
                total_samples += 1
                float_eval = evaluator.evaluate_float_residual(point)
                if float_eval.evaluation_status is not EvaluationStatus.OK:
                    continue
                finite_samples += 1
                guard_ok, _violations = evaluator.evaluate_guard(point)
                if not guard_ok:
                    continue
                guard_pass_samples += 1
                if float_eval.residual_norm_float < best_residual:
                    best_residual = float_eval.residual_norm_float
                    best_point = tuple(point)
                next_candidate_id += 1
                records.append(
                    FloatCandidate(
                        x_float=tuple(point),
                        score=(float_eval.residual_norm_float * float_eval.residual_norm_float),
                        residual_norm_float=float_eval.residual_norm_float,
                        guard_ok=True,
                        evaluation_status=float_eval.evaluation_status,
                        origin_seed=-1,
                        origin_start_point_index=int(sample_index),
                        candidate_id=int(next_candidate_id),
                        hard_feasible=True,
                        hard_violation_tags=(),
                        validity_margin_float=None,
                    )
                )
                seen_points.add(point_key)

        metrics = {
            "total_points": total_samples,
            "finite_ratio": 0.0 if total_samples == 0 else (finite_samples / total_samples),
            "guard_pass_ratio": 0.0 if total_samples == 0 else (guard_pass_samples / total_samples),
            "best_residual": None if best_point is None else best_residual,
            "best_point": best_point,
        }
        # Backwards-compatible Phase 0 metric aliases used by older diagnostics.
        metrics["total_exact_distance_manifold_points"] = total_samples
        metrics["finite_exact_distance_manifold_ratio"] = metrics["finite_ratio"]
        metrics["guard_pass_exact_distance_manifold_ratio"] = metrics["guard_pass_ratio"]
        metrics["best_exact_distance_manifold_residual"] = metrics["best_residual"]
        metrics["best_exact_distance_manifold_point"] = metrics["best_point"]
        return ManifoldSampleResult(
            strategy_id=self.strategy_id,
            candidates=tuple(records),
            metrics=metrics,
        )


DEFAULT_MANIFOLD_SAMPLE_STRATEGIES: tuple[ManifoldSampleStrategy, ...] = (
    DistanceCircleSampler(),
)


def augment_with_manifold_samples(
    *,
    bundle: ProblemBundle,
    evaluator: EvaluatorPort,
    bounds: list[tuple[float, float]],
    candidates: tuple[FloatCandidate, ...],
    metrics: dict[str, object],
    strategies: tuple[ManifoldSampleStrategy, ...] = DEFAULT_MANIFOLD_SAMPLE_STRATEGIES,
) -> tuple[tuple[FloatCandidate, ...], dict[str, object]]:
    """Apply all structure-aware samplers and merge their diagnostics."""

    merged_candidates = list(candidates)
    merged_metrics = dict(metrics)
    strategy_metrics: dict[str, object] = {}
    for strategy in strategies:
        result = strategy.sample(
            bundle=bundle,
            evaluator=evaluator,
            bounds=bounds,
            existing_candidates=tuple(merged_candidates),
        )
        if not result.candidates and not result.metrics:
            continue
        merged_candidates.extend(result.candidates)
        strategy_metrics[result.strategy_id] = result.metrics
        # Keep legacy flat metric names for existing summaries/tests.
        for key, value in result.metrics.items():
            if key.startswith("total_exact_") or key.startswith("finite_exact_") or key.startswith("guard_pass_exact_") or key.startswith("best_exact_"):
                merged_metrics[key] = value
    if strategy_metrics:
        existing_sampling = merged_metrics.get("manifold_sampling")
        if isinstance(existing_sampling, dict):
            sampling = dict(existing_sampling)
            sampling.update(strategy_metrics)
        else:
            sampling = strategy_metrics
        merged_metrics["manifold_sampling"] = sampling
    return tuple(merged_candidates), merged_metrics
