"""Frozen bootstrap-index contract for EXP-LOCAL-003.

The generated bytes, rather than the counter seed, are the authority once C1
materializes them.  This module is deliberately independent of the case
generator and of assessor truth construction.
"""

from __future__ import annotations

import hashlib
import struct
from dataclasses import dataclass
from typing import Final, Literal


Stage = Literal["development", "locked"]

FAMILY_IDS: Final[tuple[str, ...]] = (
    "SCALE-LADDER",
    "CURVED-CHAIN",
    "NEAR-RANK-DEFICIENT",
    "REDUNDANT-OVERDETERMINED",
    "TANGENT-CIRCLE-LINE",
    "MULTIROOT-WARPED",
    "STRICT-GUARD-BOUNDARY",
    "OPAQUE-TRANSCENDENTAL-C0",
)
REPLICATE_COUNT: Final = 100_000
MAGIC: Final = b"GTLOCAL3BOOT1"
COUNTER_DOMAIN: Final = b"geotarget.exp-local-003.bootstrap.counter.v1\0"
COUNTER_SEED: Final = hashlib.sha256(
    b"EXP-LOCAL-003-BOOTSTRAP-SEED-V1"
).digest()
HEADER_SIZE: Final = len(MAGIC) + 1 + 1 + 4 + 4 + 4


class BootstrapFormatError(ValueError):
    """The persisted bootstrap table does not match the frozen byte format."""


def _stage_parameters(stage: Stage) -> tuple[bytes, int]:
    if stage == "development":
        return b"D", 2
    if stage == "locked":
        return b"L", 4
    raise BootstrapFormatError(f"unsupported bootstrap stage: {stage!r}")


def _draw(stage_byte: bytes, replicate: int, family: int, draw: int, groups: int) -> int:
    rejection = 0
    limit = (1 << 64) - ((1 << 64) % groups)
    prefix = (
        COUNTER_DOMAIN
        + COUNTER_SEED
        + stage_byte
        + struct.pack(">III", replicate, family, draw)
    )
    while True:
        digest = hashlib.sha256(prefix + struct.pack(">I", rejection)).digest()
        value = int.from_bytes(digest[:8], "big")
        if value < limit:
            return value % groups
        rejection += 1
        if rejection > 0xFFFFFFFF:
            raise BootstrapFormatError("bootstrap rejection counter exhausted")


def bootstrap_index_bytes(stage: Stage) -> bytes:
    """Return the exact complete header-plus-payload byte string for *stage*.

    Payload order is replicate outermost, family ordinal next, draw innermost.
    Every payload element is one unsigned byte.
    """

    stage_byte, groups = _stage_parameters(stage)
    header = (
        MAGIC
        + b"\0"
        + stage_byte
        + struct.pack(">III", REPLICATE_COUNT, len(FAMILY_IDS), groups)
    )
    payload = bytearray(REPLICATE_COUNT * len(FAMILY_IDS) * groups)
    offset = 0
    for replicate in range(REPLICATE_COUNT):
        for family in range(len(FAMILY_IDS)):
            for draw in range(groups):
                payload[offset] = _draw(stage_byte, replicate, family, draw, groups)
                offset += 1
    return header + payload


def bootstrap_sha256(stage: Stage) -> str:
    """SHA-256 of the complete frozen table for *stage*."""

    return hashlib.sha256(bootstrap_index_bytes(stage)).hexdigest()


@dataclass(frozen=True)
class BootstrapIndexTable:
    stage: Stage
    groups_per_family: int
    payload: memoryview
    sha256: str

    def index(self, replicate: int, family_ordinal: int, draw: int) -> int:
        if not 0 <= replicate < REPLICATE_COUNT:
            raise IndexError("bootstrap replicate out of range")
        if not 0 <= family_ordinal < len(FAMILY_IDS):
            raise IndexError("bootstrap family ordinal out of range")
        if not 0 <= draw < self.groups_per_family:
            raise IndexError("bootstrap draw out of range")
        offset = (
            (replicate * len(FAMILY_IDS) + family_ordinal)
            * self.groups_per_family
            + draw
        )
        return int(self.payload[offset])


def parse_bootstrap_index_bytes(
    blob: bytes,
    *,
    expected_stage: Stage,
    expected_sha256: str | None = None,
) -> BootstrapIndexTable:
    """Strictly validate and expose a persisted bootstrap table."""

    stage_byte, groups = _stage_parameters(expected_stage)
    expected_header = (
        MAGIC
        + b"\0"
        + stage_byte
        + struct.pack(">III", REPLICATE_COUNT, len(FAMILY_IDS), groups)
    )
    expected_size = HEADER_SIZE + REPLICATE_COUNT * len(FAMILY_IDS) * groups
    if len(blob) != expected_size:
        raise BootstrapFormatError(
            f"bootstrap byte length {len(blob)} != frozen {expected_size}"
        )
    if blob[:HEADER_SIZE] != expected_header:
        raise BootstrapFormatError("bootstrap header differs from frozen contract")
    digest = hashlib.sha256(blob).hexdigest()
    if expected_sha256 is not None and digest != expected_sha256:
        raise BootstrapFormatError("bootstrap SHA-256 mismatch")
    payload = memoryview(blob)[HEADER_SIZE:]
    if any(value >= groups for value in payload):
        raise BootstrapFormatError("bootstrap payload contains an out-of-range index")
    return BootstrapIndexTable(expected_stage, groups, payload, digest)
