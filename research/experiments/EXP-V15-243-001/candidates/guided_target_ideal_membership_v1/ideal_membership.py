_ALLOWED_CALLS = frozenset(
    {
        "Area2",
        "Center",
        "Centroid",
        "Circle",
        "Collinear",
        "CoordinateX",
        "CoordinateY",
        "Dot",
        "Line",
        "MidPoint",
        "Midpoint",
        "OnLine",
        "Parallel",
        "ParallelLine",
        "Perpendicular",
        "PerpendicularLine",
        "Point",
        "PointOnSegment",
        "Reflect",
        "SignedArea2",
        "Vector",
    }
)
_ZERO_EQUIVALENT_CALLS = frozenset(
    {"Collinear", "OnLine", "Parallel", "Perpendicular"}
)


class _StrictCompiler(EXACT.Compiler):
    """Narrow direct reuse of the current compiler expression semantics."""

    def eval(self, node: ast.AST, source: str) -> Any:
        if isinstance(node, (ast.List, ast.Tuple, ast.Subscript, ast.Compare)):
            raise EXACT.Unsupported(f"container/selector/comparison is outside v1 at {source}")
        if isinstance(node, ast.Call):
            if not isinstance(node.func, ast.Name) or node.func.id not in _ALLOWED_CALLS:
                name = node.func.id if isinstance(node.func, ast.Name) else type(node.func).__name__
                raise EXACT.Unsupported(f"call {name} is outside safe subset v1 at {source}")
            if node.keywords:
                raise EXACT.Unsupported(f"keyword options are outside safe subset v1 at {source}")
            name = node.func.id
            if name == "Reflect":
                if len(node.args) != 2:
                    raise EXACT.Unsupported(f"Reflect arity is outside safe subset v1 at {source}")
                value, center = (self.eval(item, source) for item in node.args)
                if not isinstance(value, EXACT.Point) or not isinstance(center, EXACT.Point):
                    raise EXACT.Unsupported(f"only point-center Reflect is safe in v1 at {source}")
                return EXACT.Point(2 * center.x - value.x, 2 * center.y - value.y)
            if name in {"Area2", "SignedArea2"}:
                points = [self.eval(item, source) for item in node.args]
                if len(points) < 3 or not all(isinstance(item, EXACT.Point) for item in points):
                    raise EXACT.Unsupported(f"signed area2 needs points at {source}")
                return sp.expand(
                    sum(
                        points[index].x * points[(index + 1) % len(points)].y
                        - points[index].y * points[(index + 1) % len(points)].x
                        for index in range(len(points))
                    )
                )
            if name in {"CoordinateX", "CoordinateY"}:
                if len(node.args) != 1:
                    raise EXACT.Unsupported(f"coordinate arity is outside v1 at {source}")
                value = self.eval(node.args[0], source)
                if not isinstance(value, EXACT.Point):
                    raise EXACT.Unsupported(f"coordinate object is not a point at {source}")
                return value.x if name == "CoordinateX" else value.y
        return super().eval(node, source)


@dataclass(frozen=True)
class _Lowered:
    expression: sp.Expr
    zero_equivalent_only: bool


@dataclass(frozen=True)
class _AdoptedEquation:
    ordinal: int
    expression: sp.Expr
    node_sha256: str
    operation_signature: str


def _fraction_text(value: Fraction) -> str:
    return str(value.numerator) if value.denominator == 1 else f"{value.numerator}/{value.denominator}"


def rational_candidate_from_descriptor(descriptor: object) -> tuple[Fraction, dict[str, object]]:
    if not isinstance(descriptor, Mapping):
        raise ProofOnlyRejected("ordinary descriptor is absent")
    coefficients = descriptor.get("minimal_polynomial_high_to_low")
    if (
        not isinstance(coefficients, list)
        or len(coefficients) != 2
        or any(not isinstance(item, int) or isinstance(item, bool) for item in coefficients)
        or coefficients[0] <= 0
        or gcd(abs(coefficients[0]), abs(coefficients[1])) != 1
        or descriptor.get("selected_real_root_index") != 0
    ):
        raise ProofOnlyRejected("ordinary descriptor is not a degree-one exact relation")
    value = Fraction(-coefficients[1], coefficients[0])
    isolator = descriptor.get("isolating_interval")
    if not isinstance(isolator, Mapping):
        raise ProofOnlyRejected("ordinary rational isolator is absent")
    if isolator.get("multiplicity") != 1 or isolator.get("real_root_index") != 0:
        raise ProofOnlyRejected("ordinary rational isolator ordinal/multiplicity is malformed")
    try:
        left = Fraction(str(isolator.get("left")))
        right = Fraction(str(isolator.get("right")))
    except (ValueError, TypeError, ZeroDivisionError) as error:
        raise ProofOnlyRejected("ordinary rational isolator is malformed") from error
    if not left <= value <= right:
        raise ProofOnlyRejected("ordinary rational root lies outside its isolator")
    relation = {
        "coefficients_high_to_low": coefficients,
        "selected_real_root_index": 0,
        "isolating_interval": {"left": str(left), "right": str(right)},
        "rational_root": _fraction_text(value),
    }
    return value, relation


def _ast_sha(ordinal: int, left: str, right: str) -> str:
    left_tree = ast.parse(left, mode="eval")
    right_tree = ast.parse(right, mode="eval")
    return _canonical_sha256(
        {
            "source_constraint_ordinal": ordinal,
            "left_ast": ast.dump(left_tree.body, annotate_fields=True, include_attributes=False),
            "right_ast": ast.dump(right_tree.body, annotate_fields=True, include_attributes=False),
        }
    )


def _call_signature(tree: ast.AST) -> str:
    calls = sorted(
        {
            node.func.id
            for node in ast.walk(tree)
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
        }
    )
    return "+".join(calls) if calls else "polynomial-arithmetic"


class _SubsetLowerer:
    def __init__(self, document: Mapping[str, Any]) -> None:
        variables = document.get("variables")
        names = variables.get("names") if isinstance(variables, Mapping) else None
        if (
            not isinstance(names, list)
            or not 1 <= len(names) <= MAX_VARIABLES
            or not all(isinstance(name, str) and name for name in names)
            or len(set(names)) != len(names)
        ):
            raise ProofOnlyRejected("source variable ledger is outside v1")
        self.names = tuple(names)
        self.backend = _StrictCompiler({"variables": {"names": list(names)}})
        self.symbols = tuple(self.backend.symbols[name] for name in names)
        self._seen = set(names)

    @staticmethod
    def _has_relation_call(tree: ast.AST) -> bool:
        return any(
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id in _ZERO_EQUIVALENT_CALLS
            for node in ast.walk(tree)
        )

    def _trial_eval(self, tree: ast.AST, source: str) -> Any:
        trial = copy.deepcopy(self.backend)
        initial_unknowns = len(trial.unknowns)
        initial_equations = len(trial.equations)
        initial_reconstruction = len(trial.reconstruction)
        initial_replay = len(trial.replay)
        value = trial.eval(tree, source)
        if (
            len(trial.unknowns) != initial_unknowns
            or len(trial.equations) != initial_equations
            or len(trial.reconstruction) != initial_reconstruction
            or len(trial.replay) != initial_replay
        ):
            raise ProofOnlyRejected("auxiliary/squared/division cover is outside safe subset v1")
        return trial, value

    def construction(self, records: object) -> dict[str, int]:
        counts = {"supported": 0, "ignored": 0}
        if not isinstance(records, list):
            raise ProofOnlyRejected("construction is not a sequential list")
        for ordinal, record in enumerate(records):
            if (
                not isinstance(record, Mapping)
                or not isinstance(record.get("name"), str)
                or not isinstance(record.get("expr"), str)
                or record["name"] in self._seen
            ):
                raise ProofOnlyRejected("construction ledger is malformed")
            self._seen.add(record["name"])
            try:
                tree = ast.parse(record["expr"], mode="eval").body
                trial, value = self._trial_eval(tree, f"construction:{ordinal}")
                trial.context[record["name"]] = value
                self.backend = trial
                counts["supported"] += 1
            except (EXACT.Unsupported, ProofOnlyRejected, SyntaxError, TypeError, ValueError):
                counts["ignored"] += 1
        return counts

    def scalar(self, text: object, source: str) -> _Lowered:
        if not isinstance(text, str) or not text.strip():
            raise ProofOnlyRejected("scalar expression is malformed")
        tree = ast.parse(text, mode="eval").body
        relation_calls = self._has_relation_call(tree)
        top_relation = bool(
            isinstance(tree, ast.Call)
            and isinstance(tree.func, ast.Name)
            and tree.func.id in _ZERO_EQUIVALENT_CALLS
        )
        if relation_calls and not top_relation:
            raise ProofOnlyRejected("scaled/nested line relation is outside v1")
        _trial, value = self._trial_eval(tree, source)
        if not isinstance(value, sp.Expr):
            raise ProofOnlyRejected("expression is not scalar")
        value = sp.cancel(value)
        if value.has(sp.Float) or value.atoms(sp.Function):
            raise ProofOnlyRejected("non-QQ expression is outside v1")
        numerator, denominator = sp.fraction(sp.together(value))
        if denominator.free_symbols or denominator == 0:
            raise ProofOnlyRejected("symbolic or zero denominator is outside v1")
        normalized = sp.expand(numerator / denominator)
        polynomial = sp.Poly(normalized, *self.symbols, domain=sp.QQ)
        if polynomial.total_degree() > MAX_DEGREE or len(polynomial.terms()) > MAX_TERMS:
            raise ProofOnlyRejected("polynomial cap exceeded")
        return _Lowered(polynomial.as_expr(), relation_calls)


def _cofactor_witness(
    equations: Sequence[sp.Expr],
    target_relation: sp.Expr,
    symbols: Sequence[sp.Symbol],
) -> tuple[sp.Expr, ...] | None:
    for cofactor_degree in (0, 1, 2):
        monomials = sorted(
            sp.polys.monomials.itermonomials(symbols, cofactor_degree),
            key=sp.default_sort_key,
        )
        if len(monomials) * len(equations) > MAX_COFACTOR_UNKNOWNS:
            break
        unknowns = sp.symbols(f"__cofactor_0:{len(monomials) * len(equations)}")
        cofactors = []
        offset = 0
        for _equation in equations:
            coefficients = unknowns[offset : offset + len(monomials)]
            cofactors.append(sum(c * m for c, m in zip(coefficients, monomials)))
            offset += len(monomials)
        residual = sp.expand(
            sum(cofactor * equation for cofactor, equation in zip(cofactors, equations))
            - target_relation
        )
        coefficient_equations = [
            coefficient
            for _monomial, coefficient in sp.Poly(
                residual, *symbols, domain=sp.QQ.frac_field(*unknowns)
            ).terms()
        ]
        solution_set = sp.linsolve(coefficient_equations, unknowns)
        if solution_set is sp.EmptySet:
            continue
        try:
            solution = next(iter(solution_set))
        except StopIteration:
            continue
        free = set().union(*(item.free_symbols for item in solution)) - set(symbols)
        substitutions = {symbol: 0 for symbol in free}
        solved = tuple(sp.expand(item.subs(dict(zip(unknowns, solution))).subs(substitutions)) for item in cofactors)
        if sp.expand(sum(h * g for h, g in zip(solved, equations)) - target_relation) == 0:
            return solved
    return None


def _unproved(reason: str, *, source_sha256: str, elapsed: float) -> dict[str, object]:
    return {
        "schema_version": SCHEMA,
        "status": "SUBSET_IDENTITY_NOT_PROVED",
        "reason": reason,
        "source_sha256": source_sha256,
        "authority_pass": False,
        "target_release": False,
        "regular_root_evidence_required": True,
        "truth_used": False,
        "elapsed_wall_seconds": elapsed,
    }


def _prove_subset_identity_document(
    document: object,
    *,
    source_sha256: str,
    rational_target: Fraction,
    candidate_relation: Mapping[str, object],
    ordinary_proposal_sha256: str,
    timeout_seconds: float = 3.0,
) -> dict[str, object]:
    started = time.monotonic()
    try:
        if not isinstance(document, Mapping) or document.get("task") != "solve":
            raise ProofOnlyRejected("raw solve source is required")
        if document.get("post_process") not in (None, ""):
            raise ProofOnlyRejected("raw target with no post-process is required")
        if not isinstance(source_sha256, str) or len(source_sha256) != 64:
            raise ProofOnlyRejected("source SHA-256 binding is malformed")
        if not isinstance(ordinary_proposal_sha256, str) or len(ordinary_proposal_sha256) != 64:
            raise ProofOnlyRejected("ordinary proposal binding is malformed")
        lowerer = _SubsetLowerer(document)
        construction_counts = lowerer.construction(document.get("construction", []))
        adopted: list[_AdoptedEquation] = []
        constraints = document.get("constraints")
        if not isinstance(constraints, list):
            raise ProofOnlyRejected("source constraints are not a list")
        for ordinal, relation in enumerate(constraints):
            if time.monotonic() - started >= timeout_seconds:
                raise ProofOnlyRejected("proof deadline exceeded")
            if not isinstance(relation, Mapping) or not isinstance(relation.get("def"), str):
                continue
            left_text = relation["def"]
            right_text = relation.get("value", "0")
            if not isinstance(right_text, str):
                right_text = str(right_text)
            try:
                left = lowerer.scalar(left_text, f"constraint:{ordinal}:left")
                right = lowerer.scalar(right_text, f"constraint:{ordinal}:right")
                if left.zero_equivalent_only or right.zero_equivalent_only:
                    if left.zero_equivalent_only and not right.zero_equivalent_only and right.expression == 0:
                        expression = left.expression
                    elif right.zero_equivalent_only and not left.zero_equivalent_only and left.expression == 0:
                        expression = right.expression
                    else:
                        continue
                else:
                    expression = sp.expand(left.expression - right.expression)
                polynomial = sp.Poly(expression, *lowerer.symbols, domain=sp.QQ)
                if polynomial.is_zero:
                    continue
                if polynomial.total_degree() > MAX_DEGREE or len(polynomial.terms()) > MAX_TERMS:
                    continue
                adopted.append(
                    _AdoptedEquation(
                        ordinal=ordinal,
                        expression=polynomial.as_expr(),
                        node_sha256=_ast_sha(ordinal, left_text, right_text),
                        operation_signature=_call_signature(ast.parse(left_text, mode="eval").body),
                    )
                )
            except (EXACT.Unsupported, ProofOnlyRejected, SyntaxError, TypeError, ValueError, sp.PolynomialError):
                continue
        if not 1 <= len(adopted) <= MAX_ADOPTED_EQUATIONS:
            raise ProofOnlyRejected("adopted exact equality count is outside v1")
        target = lowerer.scalar(document.get("answer"), "raw-target")
        if target.zero_equivalent_only and rational_target != 0:
            raise ProofOnlyRejected("zero-equivalent target can prove only q=0")
        target_relation = sp.expand(target.expression - sp.Rational(rational_target.numerator, rational_target.denominator))
        equations = [item.expression for item in adopted]
        basis = sp.groebner(equations, *lowerer.symbols, order="grevlex", domain=sp.QQ)
        if any(
            polynomial.total_degree() == 0 and not polynomial.is_zero
            for polynomial in basis.polys
        ):
            raise ProofOnlyRejected("adopted subset ideal is inconsistent/unit")
        basis_quotients, remainder = basis.reduce(target_relation)
        remainder = sp.expand(remainder)
        if remainder != 0:
            return _unproved(
                "exact Groebner remainder is nonzero",
                source_sha256=source_sha256,
                elapsed=time.monotonic() - started,
            )
        basis_expressions = [item.as_expr() for item in basis.polys]
        if sp.expand(
            sum(q * b for q, b in zip(basis_quotients, basis_expressions))
            + remainder
            - target_relation
        ) != 0:
            raise ProofOnlyRejected("basis reduction witness failed exact replay")
        cofactors = _cofactor_witness(equations, target_relation, lowerer.symbols)
        if cofactors is None:
            raise ProofOnlyRejected("bounded source-equation cofactor witness unavailable")
        elapsed = time.monotonic() - started
        if elapsed > timeout_seconds:
            raise ProofOnlyRejected("proof deadline exceeded")
        statement = {
            "source_sha256": source_sha256,
            "ordinary_proposal_sha256": ordinary_proposal_sha256,
            "candidate_relation": dict(candidate_relation),
            "rational_target": _fraction_text(rational_target),
            "source_variables": list(lowerer.names),
            "adopted_source_node_hashes": [item.node_sha256 for item in adopted],
            "adopted_equations": [str(item.expression) for item in adopted],
            "raw_target_expression": str(target.expression),
            "target_minus_q": str(target_relation),
            "groebner_basis": [str(item) for item in basis_expressions],
            "basis_reduction_quotients": [str(item) for item in basis_quotients],
            "source_equation_cofactors": [str(item) for item in cofactors],
            "exact_remainder": "0",
        }
        return {
            "schema_version": SCHEMA,
            "status": "SUBSET_IDENTITY_PROVED_HOLD",
            "reason": "universal target identity proved; regular-root/guard/branch evidence not joined",
            "source_sha256": source_sha256,
            "ordinary_proposal_sha256": ordinary_proposal_sha256,
            "candidate_relation": dict(candidate_relation),
            "authority_pass": False,
            "target_release": False,
            "proof_only": True,
            "regular_root_evidence_required": True,
            "guards_branches_definedness_proved": False,
            "adopted_source_node_hashes": [item.node_sha256 for item in adopted],
            "adopted_equation_count": len(adopted),
            "ignored_constraint_count": len(constraints) - len(adopted),
            "operation_signatures": sorted({item.operation_signature for item in adopted}),
            "construction_counts": construction_counts,
            "groebner_basis_size": len(basis_expressions),
            "exact_remainder": "0",
            "cofactor_witness_complete": True,
            "statement": statement,
            "statement_sha256": _canonical_sha256(statement),
            "anonymous_structure_signature": {
                "variable_count": len(lowerer.symbols),
                "adopted_equation_count": len(adopted),
                "maximum_equation_degree": max(sp.Poly(item.expression, *lowerer.symbols).total_degree() for item in adopted),
                "target_degree": sp.Poly(target_relation, *lowerer.symbols).total_degree(),
                "operation_signature_count": len({item.operation_signature for item in adopted}),
            },
            "truth_used": False,
            "elapsed_wall_seconds": elapsed,
        }
    except Exception as error:
        reason = str(error) if isinstance(error, (ProofOnlyRejected, EXACT.Unsupported)) else f"{type(error).__name__}: {error}"
        return _unproved(reason, source_sha256=source_sha256, elapsed=time.monotonic() - started)


def prove_subset_identity(
    source_path: Path,
    *,
    ordinary_proposal: Mapping[str, object],
    timeout_seconds: float = 3.0,
) -> dict[str, object]:
    """Read and bind the immutable source plus ordinary degree-one proposal."""

    started = time.monotonic()
    try:
        payload = source_path.read_bytes()
        source_sha256 = _sha256_bytes(payload)
        document = json.loads(payload)
        if not (
            isinstance(ordinary_proposal, Mapping)
            and ordinary_proposal.get("status") == "TARGET_AUTHORITY_READY"
            and ordinary_proposal.get("authority_pass") is True
        ):
            raise ProofOnlyRejected("existing ordinary HP proposal is not ready")
        rational_target, candidate_relation = rational_candidate_from_descriptor(
            ordinary_proposal.get("descriptor")
        )
        ordinary_proposal_sha256 = _canonical_sha256(ordinary_proposal)
        remaining = timeout_seconds - (time.monotonic() - started)
        if remaining <= 0:
            raise ProofOnlyRejected("proof deadline exceeded")
        return _prove_subset_identity_document(
            document,
            source_sha256=source_sha256,
            rational_target=rational_target,
            candidate_relation=candidate_relation,
            ordinary_proposal_sha256=ordinary_proposal_sha256,
            timeout_seconds=remaining,
        )
    except Exception as error:
        reason = str(error) if isinstance(error, ProofOnlyRejected) else f"{type(error).__name__}: {error}"
        source_sha256 = (
            _sha256_bytes(source_path.read_bytes()) if source_path.is_file() else "UNAVAILABLE"
        )
        return _unproved(
            reason,
            source_sha256=source_sha256,
            elapsed=time.monotonic() - started,
        )


def verify_subset_proof(
    source_path: Path,
    *,
    ordinary_proposal: Mapping[str, object],
    artifact: Mapping[str, object],
    timeout_seconds: float = 3.0,
) -> None:
    """Recompile and replay every proof binding before a three-way join."""

    replayed = prove_subset_identity(
        source_path,
        ordinary_proposal=ordinary_proposal,
        timeout_seconds=timeout_seconds,
    )
    if replayed.get("status") != "SUBSET_IDENTITY_PROVED_HOLD":
        raise ProofOnlyRejected("subset identity does not replay")
    mandatory = (
        "schema_version",
        "status",
        "source_sha256",
        "ordinary_proposal_sha256",
        "candidate_relation",
        "adopted_source_node_hashes",
        "adopted_equation_count",
        "exact_remainder",
        "cofactor_witness_complete",
        "statement",
        "statement_sha256",
    )
    if any(artifact.get(key) != replayed.get(key) for key in mandatory):
        raise ProofOnlyRejected("subset proof artifact differs from exact replay")
    statement = artifact.get("statement")
    if not isinstance(statement, Mapping) or _canonical_sha256(statement) != artifact.get(
        "statement_sha256"
    ):
        raise ProofOnlyRejected("subset proof statement digest is invalid")
    if artifact.get("authority_pass") is not False or artifact.get("target_release") is not False:
        raise ProofOnlyRejected("proof-only artifact claims target authority")


