"""Proof-only universal target identity over a safe source-equation subset.

This module never emits target authority.  It proves only the algebraic
statement ``raw_target - q`` is in an ideal generated by exact consequences
of selected source equalities.  Root existence, regularity, source guards,
branches, and definedness remain separate mandatory proof conjuncts.
"""

